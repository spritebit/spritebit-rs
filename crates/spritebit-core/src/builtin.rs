/// Eingebaute Palette nach Namen.
pub fn builtin(name: &str) -> Option<Palette> {
    BUILTIN.iter().find(|(n, _)| *n == name).map(|(n, c)| Palette::new(*n, c.to_vec()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn alle_paletten_der_web_version_da() {
        assert_eq!(BUILTIN.len(), 17);
        let g = builtin("graustufen").unwrap();
        assert_eq!(g.get(1), Some([0xff, 0xff, 0xff]));
        assert!(builtin("gibtsnicht").is_none());
    }
}
